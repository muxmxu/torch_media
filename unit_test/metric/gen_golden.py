# D: segm with rectangle-minus-hole masks from integer parameters (mirrored in C++: make_mask)
MH, MW = 40, 48


def make_mask(p):
    x0, y0, x1, y1, hole = p
    m = torch.zeros(MH, MW, dtype=torch.uint8)
    m[y0:y1, x0:x1] = 1
    if hole:
        m[y0 + (y1 - y0) // 3:y1 - (y1 - y0) // 3, x0 + (x1 - x0) // 3:x1 - (x1 - x0) // 3] = 0
    return m


def rand_mask_params(n):
    out = []
    for _ in range(n):
        x0, y0 = int(rng.integers(0, MW - 6)), int(rng.integers(0, MH - 6))
        out.append([x0, y0, int(rng.integers(x0 + 3, MW + 1)), int(rng.integers(y0 + 3, MH + 1)), int(rng.integers(0, 2))])
    return out


def jitter_params(p):
    x0, y0, x1, y1, hole = p
    d = rng.integers(-2, 3, 4)
    x0n, y0n = int(np.clip(x0 + d[0], 0, MW - 2)), int(np.clip(y0 + d[1], 0, MH - 2))
    return [x0n, y0n, int(np.clip(x1 + d[2], x0n + 1, MW)), int(np.clip(y1 + d[3], y0n + 1, MH)), hole]


