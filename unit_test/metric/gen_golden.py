# speaker verification: EER / minDCF from sklearn's ROC with the formulas of the C++ docs
def roc_np(tar, non):
    fpr, tpr, _ = sklearn.metrics.roc_curve(np.r_[np.ones(len(tar)), np.zeros(len(non))], np.r_[tar, non],
                                            drop_intermediate=False)
    return fpr, 1 - tpr


def eer_np(tar, non):
    fpr, fnr = roc_np(tar, non)
    d = fnr - fpr
    i = int(np.argmax(d <= 0))
    if d[i] == 0:
        return fpr[i]
    t = d[i - 1] / (d[i - 1] - d[i])
    return fpr[i - 1] + t * (fpr[i] - fpr[i - 1])


def min_dcf_np(tar, non, p_target=0.01, c_miss=1.0, c_fa=1.0):
    fpr, fnr = roc_np(tar, non)
    c_det = c_miss * fnr * p_target + c_fa * fpr * (1 - p_target)
    return np.min(c_det) / min(c_miss * p_target, c_fa * (1 - p_target))


