def make_dataset(n_img, labels, max_gt, max_extra, crowd_p, *, only_pred=None, only_gt=None, area_p=0.0,
                 empty_pred_p=0.1, empty_gt_p=0.1, img=(480, 640)):
    H, W = img
    preds, target = [], []
    for i in range(n_img):
        gb, gl, gc, ga = [], [], [], []
        ng = 0 if rng.uniform() < empty_gt_p else int(rng.integers(1, max_gt + 1))
        for _ in range(ng):
            size = rng.choice([rng.uniform(4, 31), rng.uniform(33, 95), rng.uniform(97, 300)])
            ar = rng.uniform(0.5, 2.0)
            w, h = size * np.sqrt(ar), size / np.sqrt(ar)
            x, y = rng.uniform(0, W - w), rng.uniform(0, H - h)
            gb.append([x, y, x + w, y + h])
            gl.append(int(rng.choice(labels)))
            gc.append(int(rng.uniform() < crowd_p))
            ga.append(float(np.float32(w * h * rng.uniform(0.6, 1.0))) if rng.uniform() < area_p else 0.0)
        if only_gt is not None and rng.uniform() < 0.3:
            gb.append([10.0, 10.0, 60.0, 70.0]); gl.append(only_gt); gc.append(0); ga.append(0.0)
        db, dl, ds = [], [], []
        if rng.uniform() >= empty_pred_p:
            for b, l in zip(gb, gl):
                for _ in range(int(rng.integers(0, 3))):
                    j = rng.normal(0, 0.12, 4) * np.array([b[2] - b[0], b[3] - b[1]] * 2)
                    db.append([b[0] + j[0], b[1] + j[1], max(b[2] + j[2], b[0] + j[0] + 1), max(b[3] + j[3], b[1] + j[1] + 1)])
                    dl.append(l if rng.uniform() < 0.9 else int(rng.choice(labels)))
                    ds.append(round(float(rng.uniform(0.3, 1.0)), 2))
            for _ in range(int(rng.integers(0, max_extra + 1))):
                w, h = rng.uniform(4, 200), rng.uniform(4, 200)
                x, y = rng.uniform(0, W - w), rng.uniform(0, H - h)
                db.append([x, y, x + w, y + h])
                dl.append(int(rng.choice(labels)))
                ds.append(round(float(rng.uniform(0.0, 0.8)), 2))
            if only_pred is not None and rng.uniform() < 0.3:
                db.append([100.0, 100.0, 180.0, 150.0]); dl.append(only_pred); ds.append(0.55)
            if len(ds) >= 2 and rng.uniform() < 0.3:
                ds[-1] = ds[0]  # an exact score tie in one image
        preds.append(dict(boxes=torch.tensor(db, dtype=torch.float32).reshape(-1, 4),
                          scores=torch.tensor(ds, dtype=torch.float32), labels=torch.tensor(dl, dtype=torch.int64)))
        t = dict(boxes=torch.tensor(gb, dtype=torch.float32).reshape(-1, 4), labels=torch.tensor(gl, dtype=torch.int64),
                 iscrowd=torch.tensor(gc, dtype=torch.int64))
        if area_p > 0:
            t["area"] = torch.tensor(ga, dtype=torch.float32)
        target.append(t)
    return preds, target


def emit_dataset(name, preds, target):
    emit(f"{name}_pred_boxes", torch.cat([p["boxes"] for p in preds]).reshape(-1, 4))
    emit(f"{name}_pred_scores", torch.cat([p["scores"] for p in preds]))
    emit(f"{name}_pred_labels", torch.cat([p["labels"] for p in preds]))
    emit(f"{name}_pred_counts", torch.tensor([len(p["labels"]) for p in preds]))
    emit(f"{name}_gt_boxes", torch.cat([t["boxes"] for t in target]).reshape(-1, 4))
    emit(f"{name}_gt_labels", torch.cat([t["labels"] for t in target]))
    emit(f"{name}_gt_crowd", torch.cat([t["iscrowd"] for t in target]))
    emit(f"{name}_gt_area", torch.cat([t.get("area", torch.zeros(len(t["labels"]))) for t in target]))
    emit(f"{name}_gt_counts", torch.tensor([len(t["labels"]) for t in target]))


def coco_golden(name, preds, target, *, box_format="xyxy", iou_type="bbox", iou_thresholds=None, rec_thresholds=None,
                max_dets=None, average="macro", class_metrics=False):
    """pycocotools COCOeval float64 stats on torchmetrics' COCO conversion; asserts torchmetrics agrees in float32."""
    iou_thr = iou_thresholds or torch.linspace(0.5, 0.95, round((0.95 - 0.5) / 0.05) + 1).tolist()
    rec_thr = rec_thresholds or torch.linspace(0.0, 1.00, round(1.00 / 0.01) + 1).tolist()
    mdt = torch.sort(torch.tensor(max_dets or [1, 10, 100], dtype=torch.int))[0].tolist()
    backend = CocoBackend("pycocotools")
    det = {"box": [], "mask": [], "labels": [], "scores": []}
    gt = {"box": [], "mask": [], "labels": [], "crowds": [], "area": []}
    for p in preds:
        b, m = _get_safe_item_values((iou_type,), box_format, mdt, backend, p)
        if b is not None: det["box"].append(b)
        if m is not None: det["mask"].append(m)
        det["labels"].append(p["labels"]); det["scores"].append(p["scores"])
    for t in target:
        b, m = _get_safe_item_values((iou_type,), box_format, mdt, backend, t)
        if b is not None: gt["box"].append(b)
        if m is not None: gt["mask"].append(m)
        gt["labels"].append(t["labels"])
        gt["crowds"].append(t.get("iscrowd", torch.zeros_like(t["labels"])))
        gt["area"].append(t.get("area", torch.zeros_like(t["labels"])))

    def run(avg, cats=None):
        cp, ct = backend._get_coco_datasets(gt["labels"], gt["box"], gt["mask"], gt["crowds"], gt["area"], det["labels"],
                                            det["box"], det["mask"], det["scores"], (iou_type,), average=avg)
        if len(cp.imgs) == 0 or len(ct.imgs) == 0:
            return None
        ev = COCOeval(ct, cp, iouType=iou_type)
        ev.params.iouThrs = np.array(iou_thr, dtype=np.float64)
        ev.params.recThrs = np.array(rec_thr, dtype=np.float64)
        ev.params.maxDets = mdt
        out = []
        for c in cats or [None]:
            if c is not None:
                ev.params.catIds = [c]
            with contextlib.redirect_stdout(io.StringIO()):
                ev.evaluate(); ev.accumulate(); ev.summarize()
            out.append(ev.stats.copy())
        return out

    res = run(average)
    stats = res[0] if res else np.full(12, -1.0)
    classes = _get_classes(det["labels"], gt["labels"])
    emit(name, torch.tensor(stats, dtype=torch.float64))
    pc = run("macro", classes) if class_metrics and res else None
    if pc is not None:
        emit(f"{name}_map_pc", torch.tensor([s[0] for s in pc], dtype=torch.float64))
        emit(f"{name}_mar_pc", torch.tensor([s[8] for s in pc], dtype=torch.float64))
    emit(f"{name}_classes", torch.tensor(classes, dtype=torch.int64))
    # torchmetrics (float32) must equal the float64 stats rounded
    tm = MeanAveragePrecision(box_format=box_format, iou_type=iou_type, iou_thresholds=iou_thresholds,
                              rec_thresholds=rec_thresholds, max_detection_thresholds=max_dets,
                              class_metrics=class_metrics, average=average)
    tm.update(preds, target)
    r = tm.compute()
    keys = ["map", "map_50", "map_75", "map_small", "map_medium", "map_large", f"mar_{mdt[0]}", f"mar_{mdt[1]}",
            f"mar_{mdt[2]}", "mar_small", "mar_medium", "mar_large"]
    for k, v in zip(keys, stats):
        assert r[k].item() == np.float32(v), (name, k, r[k].item(), v)
    if pc is not None:
        assert torch.equal(r["map_per_class"].reshape(-1), torch.tensor([s[0] for s in pc], dtype=torch.float32))
        assert torch.equal(r[f"mar_{mdt[2]}_per_class"].reshape(-1), torch.tensor([s[8] for s in pc], dtype=torch.float32))
    return stats


def convert(preds, target, fmt):
    cv = lambda d: {**d, "boxes": ops.box_convert(d["boxes"], "xyxy", fmt)}
    return [cv(p) for p in preds], [cv(t) for t in target]


