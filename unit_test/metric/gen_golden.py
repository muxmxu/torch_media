# A zero-filled 0.5 s dropout over speech in the prediction: extended STOI's segments inside it have zero band
# envelopes, and the segments with one speech frame next to it have rows that normalise to the same vector (columns
# constant up to rounding). pystoi's EPS * N(0, 1) dither turns those rows / columns into random unit vectors (a
# random value of mean 0); the golden is pystoi with that dither removed and rows / columns whose spread is <= 1e-13
# of their norm scaled by 0 (progress01 D7), checked against the mean of seeded pystoi runs.
import pystoi
import pystoi.utils


def row_col_normalize_expected(x):
    def center_scale(x, axis):
        c = x - np.mean(x, axis=axis, keepdims=True)
        n = np.sqrt(np.sum(np.square(c), axis=axis, keepdims=True))
        keep = n > 1e-13 * np.sqrt(np.sum(np.square(x), axis=axis, keepdims=True))
        return c * np.where(keep, 1 / np.where(keep, n, 1), 0)
    return center_scale(center_scale(x, -1), 1)


