def speech(n, fs, seed):
    """Speech-like float64 signal: a jittered ~120 Hz pulse train plus breath noise through two resonators, in 1/4 s
    syllables with every third one silent (exact zeros). Only + - * / in Python float order: C++ reproduces it."""
    u = splitmix_u(n, seed).tolist()
    period, syl = fs // 120, fs // 4
    out = [0.0] * n
    y1 = y2 = z1 = z2 = 0.0
    nxt = 0
    for t in range(n):
        e = (u[t] - 0.5) * 0.02
        if t == nxt:
            e = e + 1.0
            nxt = t + period + int(u[t] * 8.0)
        y = 1.3 * y1 - 0.85 * y2 + e
        y2, y1 = y1, y
        z = 0.4 * z1 - 0.6 * z2 + y
        z2, z1 = z1, z
        k = t % syl
        env = 0.0 if (t // syl) % 3 == 2 else (k / syl) * (1.0 - k / syl) * 4.0
        out[t] = z * env
    return np.array(out)


