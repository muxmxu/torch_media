# ---------------------------------------------------------------- splitmix64 inputs (mirrored in C++)
def splitmix_u(n, seed):
    i = np.arange(1, n + 1, dtype=np.uint64)
    z = np.uint64(seed) + i * np.uint64(0x9E3779B97F4A7C15)
    z = (z ^ (z >> np.uint64(30))) * np.uint64(0xBF58476D1CE4E5B9)
    z = (z ^ (z >> np.uint64(27))) * np.uint64(0x94D049BB133111EB)
    z = z ^ (z >> np.uint64(31))
    return (z >> np.uint64(11)).astype(np.float64) * 2.0 ** -53


def image_pair(shape, seed):
    """(preds, target) float64 in [0, 1]: target = 8x8 blocks + fine noise, preds = target + noise, clipped."""
    n = int(np.prod(shape))
    h, w = shape[-2], shape[-1]
    fine = splitmix_u(n, seed).reshape(shape)
    coarse = splitmix_u(n, seed + 1).reshape(shape)
    yy = (np.arange(h) // 8) * 8
    xx = (np.arange(w) // 8) * 8
    block = coarse[..., yy[:, None], xx[None, :]]
    target = 0.6 * block + 0.3 * fine + 0.05
    noise = splitmix_u(n, seed + 2).reshape(shape)
    preds = np.clip(target + 0.15 * (noise - 0.5), 0.0, 1.0)
    return torch.from_numpy(preds), torch.from_numpy(target)


def seg_pair(n, c, h, w, seed):
    """index (preds, target) int64 [n, h, w]: sample s uses classes 0 .. k_s - 1, preds agree with target ~60%."""
    ks = np.array([c, max(1, c - 2), max(1, c - 1), max(1, c - 3)] * n)[:n].astype(np.float64)
    u1 = splitmix_u(n * h * w, seed).reshape(n, h, w)
    u2 = splitmix_u(n * h * w, seed + 1).reshape(n, h, w)
    u3 = splitmix_u(n * h * w, seed + 2).reshape(n, h, w)
    target = np.floor(u1 * ks[:, None, None])
    other = np.floor(u3 * ks[:, None, None])
    preds = np.where(u2 < 0.6, target, other)
    return torch.from_numpy(preds.astype(np.int64)), torch.from_numpy(target.astype(np.int64))


def checksum(name, x):
    x = torch.as_tensor(x, dtype=torch.float64).flatten()
    emit(name, torch.stack([x.sum(), x[0], x[x.numel() // 2], x[-1]]))


