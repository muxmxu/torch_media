def emit(name, t):
    t = torch.as_tensor(t).detach().cpu()
    if t.dtype == torch.float32:
        vals = [f"{v:.9g}" for v in t.flatten().tolist()]
    elif t.dtype in (torch.float64, torch.float16):
        vals = [repr(float(v)) for v in t.flatten().tolist()]
    elif t.dtype == torch.bool:
        vals = [str(int(v)) for v in t.flatten().tolist()]
    else:
        vals = [str(int(v)) for v in t.flatten().tolist()]
    vals = [v.replace("inf", "INFINITY").replace("nan", "NAN") for v in vals]
    shape = ", ".join(str(s) for s in t.shape)
    dtype = str(t.dtype).removeprefix("torch.")
    entries[area].append(f'    inline const entry {name}{{"{dtype}", {{{shape}}}, {{{", ".join(vals)}}}}};')


